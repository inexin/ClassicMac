    private static void Check(uint word, string expected)
    {
        var instruction = PpcDisassembler.Decode(word, 0x1000);
        Assert.Equal(expected, instruction.Text);
        Assert.Equal(word, instruction.Word);
        Assert.Equal(0x1000u, instruction.Address);
        Assert.Equal(PpcFlow.None, instruction.Flow);
        Assert.Null(instruction.Target);
        Assert.Equal(!expected.StartsWith(".long", StringComparison.Ordinal), instruction.IsValid);
    }

