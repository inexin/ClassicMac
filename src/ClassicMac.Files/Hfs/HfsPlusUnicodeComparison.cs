    internal static int Compare(ReadOnlySpan<char> left, ReadOnlySpan<char> right)
    {
        int leftIndex = 0;
        int rightIndex = 0;
        while (true)
        {
            ushort leftValue = Next(left, ref leftIndex);
            ushort rightValue = Next(right, ref rightIndex);
            int comparison = leftValue.CompareTo(rightValue);
            if (comparison != 0 || leftValue == 0) return comparison;
        }
    }

    internal static int CompareBigEndian(ReadOnlySpan<byte> left, ReadOnlySpan<byte> right)
    {
        int leftIndex = 0;
        int rightIndex = 0;
        while (true)
        {
            ushort leftValue = NextBigEndian(left, ref leftIndex);
            ushort rightValue = NextBigEndian(right, ref rightIndex);
            int comparison = leftValue.CompareTo(rightValue);
            if (comparison != 0 || leftValue == 0) return comparison;
        }
    }

